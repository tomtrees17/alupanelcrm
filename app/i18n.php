function current_lang(): string
{
    $lang = $_SESSION['lang'] ?? 'zh';
    return in_array($lang, ['zh', 'id'], true) ? $lang : 'zh';
}

function t(string $key): string
{
    $lang = current_lang();
    return I18N[$lang][$key] ?? I18N['zh'][$key] ?? $key;
}
